class AlertLogger:
    """
    Manages the formatting, routing, and persistent storage of generated security alerts.
    Provides support for standard console output, JSON Lines, and CSV log formats.
    """
    def __init__(self, out_dir: str, min_severity: str = "LOW"):
        self.out_dir = Path(out_dir)
        self.out_dir.mkdir(parents=True, exist_ok=True)
        stamp = datetime.now().strftime("%Y%m%d_%H%M%S")
        self.json_path = self.out_dir / f"pyedr_alerts_{stamp}.jsonl"
        self.csv_path = self.out_dir / f"pyedr_alerts_{stamp}.csv"
        self.min_severity = SEVERITY_ORDER.get(min_severity, 1)
        self._csv_header_written = False
        self.count = 0
        self.count_by_severity = {k: 0 for k in SEVERITY_ORDER}

    def log(self, alert: Alert):
        """
        Processes a single Alert, routing it to console output and all persistent log files
        if it meets the configured minimum severity threshold.

        Args:
            alert: The Alert object to be logged.
        """
        if SEVERITY_ORDER.get(alert.severity, 0) < self.min_severity:
            return
        alert.print_console()
        self.count += 1
        self.count_by_severity[alert.severity] = self.count_by_severity.get(alert.severity, 0) + 1

        with open(self.json_path, "a", encoding="utf-8") as f:
            f.write(json.dumps(alert.to_dict()) + "\n")

        write_header = not self._csv_header_written
        with open(self.csv_path, "a", newline="", encoding="utf-8") as f:
            writer = csv.DictWriter(f, fieldnames=list(alert.to_dict().keys()))
            if write_header:
                writer.writeheader()
                self._csv_header_written = True
            writer.writerow(alert.to_dict())

    def summary(self):
        """Prints a formatted session summary to the console, including alert counts by severity and log file paths."""
        print(f"\n{C.BOLD}{'=' * 70}{C.RESET}")
        print(f"{C.BOLD}Session Summary: {self.count} alert(s) generated{C.RESET}")
        for sev in ["CRITICAL", "HIGH", "MEDIUM", "LOW", "INFO"]:
            n = self.count_by_severity.get(sev, 0)
            if n:
                print(f"  {SEVERITY_COLOR[sev]}{sev}: {n}{C.RESET}")
        print(f"  JSON Telemetry Log : {self.json_path}")
        print(f"  CSV Telemetry Log  : {self.csv_path}")
        print(f"{C.BOLD}{'=' * 70}{C.RESET}")


