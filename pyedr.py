def collect_persistence_snapshot() -> dict:
    """
    Aggregates current state data for common OS persistence mechanisms.
    Provides graceful degradation on non-Windows platforms.
    """
    snap = {
        "run_keys": set(),
        "startup_files": set(),
        "scheduled_tasks": set(),
        "services": set(),
    }

    if not IS_WINDOWS:
        return snap

    run_key_paths = [
        (winreg.HKEY_CURRENT_USER, r"Software\Microsoft\Windows\CurrentVersion\Run"),
        (winreg.HKEY_CURRENT_USER, r"Software\Microsoft\Windows\CurrentVersion\RunOnce"),
        (winreg.HKEY_LOCAL_MACHINE, r"Software\Microsoft\Windows\CurrentVersion\Run"),
        (winreg.HKEY_LOCAL_MACHINE, r"Software\Microsoft\Windows\CurrentVersion\RunOnce"),
    ]
    if winreg:
        for hive, subkey in run_key_paths:
            try:
                with winreg.OpenKey(hive, subkey) as key:
                    i = 0
                    while True:
                        try:
                            name, value, _ = winreg.EnumValue(key, i)
                            snap["run_keys"].add(f"{subkey}\\{name} = {value}")
                            i += 1
                        except OSError:
                            break
            except FileNotFoundError:
                pass

    startup_dirs = [
        os.path.expandvars(r"%APPDATA%\Microsoft\Windows\Start Menu\Programs\Startup"),
        os.path.expandvars(r"%PROGRAMDATA%\Microsoft\Windows\Start Menu\Programs\StartUp"),
    ]
    for d in startup_dirs:
        if os.path.isdir(d):
            for f in os.listdir(d):
                snap["startup_files"].add(os.path.join(d, f))

    try:
        out = subprocess.run(
            ["schtasks", "/query", "/fo", "CSV", "/v"],
            capture_output=True, text=True, timeout=20,
        )
        if out.returncode == 0:
            reader = csv.DictReader(out.stdout.splitlines())
            for row in reader:
                name = row.get("TaskName", "")
                if name and "\\Microsoft\\" not in name and row.get("Scheduled Task State") == "Enabled":
                    snap["scheduled_tasks"].add(name)
    except Exception as e:
        print(f"{C.YELLOW}Warning: Scheduled task enumeration failed ({type(e).__name__}: {e}). Results may be incomplete.{C.RESET}")

    try:
        for svc in psutil.win_service_iter():
            info = svc.as_dict()
            if info.get("start_type") == "automatic" and info.get("status") == "running":
                snap["services"].add(f"{info.get('name')} | {info.get('binpath')}")
    except Exception as e:
        print(f"{C.YELLOW}Warning: Windows service enumeration failed ({type(e).__name__}: {e}). Results may be incomplete.{C.RESET}")

    return snap


def collect_processes() -> list:
    """
    Enumerates all currently running processes and retrieves their key attributes.
    Access-restricted processes are silently skipped to prevent collection interruption.

    Returns:
        A list of psutil process info dictionaries (pid, ppid, name, exe, cmdline).
    """
    procs = []
    for p in psutil.process_iter(["pid", "ppid", "name", "exe", "cmdline"]):
        try:
            procs.append(p.info)
        except (psutil.NoSuchProcess, psutil.AccessDenied):
            continue
    return procs


def collect_connections() -> list:
    """
    Enumerates all currently established outbound IPv4/IPv6 network connections.
    Correlates each connection to its owning process name where permissions allow.

    Returns:
        A list of connection dictionaries (pid, process_name, laddr, raddr, remote_port).
        Returns an empty list if system-level access is denied.
    """
    conns = []
    try:
        for c in psutil.net_connections(kind="inet"):
            if c.status != psutil.CONN_ESTABLISHED or not c.raddr:
                continue
            pname = None
            if c.pid:
                try:
                    pname = psutil.Process(c.pid).name()
                except (psutil.NoSuchProcess, psutil.AccessDenied):
                    pname = None
            conns.append({
                "pid": c.pid, "process_name": pname,
                "laddr": f"{c.laddr.ip}:{c.laddr.port}" if c.laddr else None,
                "raddr": f"{c.raddr.ip}:{c.raddr.port}" if c.raddr else None,
                "remote_port": c.raddr.port if c.raddr else None,
            })
    except (psutil.AccessDenied, PermissionError):
        pass
    return conns


