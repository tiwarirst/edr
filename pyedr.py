class C:
    """ANSI escape sequences for console text formatting and colorization."""
    RESET = "\033[0m"
    RED = "\033[91m"
    YELLOW = "\033[93m"
    GREEN = "\033[92m"
    CYAN = "\033[96m"
    GRAY = "\033[90m"
    BOLD = "\033[1m"
    MAGENTA = "\033[95m"

    @staticmethod
    def enable_on_windows():
        """Activates ANSI escape sequence processing on Windows terminals (cmd/PowerShell)."""
        if IS_WINDOWS:
            os.system("")  # Triggers VT100 escape processing via Win32 Console API side-effect


SEVERITY_COLOR = {
    "CRITICAL": C.RED + C.BOLD,
    "HIGH": C.RED,
    "MEDIUM": C.YELLOW,
    "LOW": C.CYAN,
    "INFO": C.GRAY,
}
SEVERITY_ORDER = {"CRITICAL": 4, "HIGH": 3, "MEDIUM": 2, "LOW": 1, "INFO": 0}


