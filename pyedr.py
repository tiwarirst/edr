@dataclass
class Alert:
    """
    Represents a discrete security alert generated by the detection engine.
    
    Attributes:
        timestamp: ISO-8601 formatted timestamp of the detection event.
        severity: Assessed severity level (e.g., CRITICAL, HIGH, MEDIUM, LOW, INFO).
        technique_id: Associated MITRE ATT&CK® technique identifier.
        technique_name: Associated MITRE ATT&CK® technique name.
        title: High-level summary of the detection.
        details: Granular technical details of the triggering event.
        source: The telemetry source that originated the alert (process/persistence/network).
    """
    timestamp: str
    severity: str
    technique_id: str
    technique_name: str
    title: str
    details: str
    source: str  # Originating telemetry source: 'process' | 'persistence' | 'network'

    def to_dict(self) -> dict:
        """Serializes the Alert instance to a dictionary for structured logging."""
        return asdict(self)

    def print_console(self):
        """Renders the alert to standard output with severity-appropriate ANSI color coding."""
        color = SEVERITY_COLOR.get(self.severity, C.RESET)
        print(f"{color}[{self.severity}] {self.technique_id} {self.technique_name}{C.RESET}")
        print(f"  {C.BOLD}{self.title}{C.RESET}")
        print(f"  {C.GRAY}{self.details}{C.RESET}")
        print(f"  {C.GRAY}@ {self.timestamp}{C.RESET}\n")


